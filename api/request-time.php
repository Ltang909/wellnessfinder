<?php
declare(strict_types=1);

/* ============================================================
   WellFinder — schedule request endpoint.

   A visitor on a clinic card asks the clinic for a time and/or
   more information (coverage billability, total cost). The email
   is sent FROM hello@wellfinder.ca with Reply-To set to the
   visitor, so the clinic's reply goes straight to them.

   The recipient is resolved SERVER-SIDE from api/clinic-contacts.json
   (generated by scripts/build_clinic_contacts.py) — the form never
   supplies or sees the clinic's address.

   Go-live needs (Leon's side, all free):
     - hello@wellfinder.ca mailbox exists + SPF/DKIM set in hPanel,
       or mail() from this host will land in spam.
     - Optional anti-spam: define WF_TURNSTILE_SECRET (string
       constant) in api/portal/config.php AND add the Turnstile
       widget to the form with the matching site key. Until the
       secret exists, verification is skipped entirely.
   ============================================================ */

function wf_out(array $payload, int $status = 200): void
{
    http_response_code($status);
    header('Content-Type: application/json; charset=utf-8');
    echo json_encode($payload);
    exit;
}

if (($_SERVER['REQUEST_METHOD'] ?? '') !== 'POST') {
    wf_out(['ok' => false, 'reason' => 'method'], 405);
}

$raw = file_get_contents('php://input');
$in = json_decode((string) $raw, true);
if (!is_array($in)) {
    wf_out(['ok' => false, 'reason' => 'bad_json'], 400);
}

$get = static function (string $k) use ($in): string {
    return isset($in[$k]) && is_string($in[$k]) ? trim($in[$k]) : '';
};
$cut = static function (string $v, int $n): string {
    return function_exists('mb_substr') ? mb_substr($v, 0, $n) : substr($v, 0, $n);
};
/* Header-bound values must never carry CR/LF. */
$flat = static function (string $v): string {
    return str_replace(["\r", "\n"], ' ', $v);
};

/* Honeypot: real users never fill the hidden "company" field.
   Pretend success, send nothing. */
if ($get('company') !== '') {
    wf_out(['ok' => true, 'caseId' => $get('caseId')]);
}

$caseId   = $get('caseId');
$userId   = $get('userId');
$clinicKey = strtolower($get('clinicKey'));
$clinicName = $flat($cut($get('clinicName'), 120));
$treatment  = $flat($cut($get('treatment'), 120));
$name     = $flat($cut($get('name'), 120));
$email    = $get('email');
$phone    = $flat($cut($get('phone'), 40));
$note     = $cut($get('note'), 1000);
$insurer  = $flat($cut($get('insurer'), 80));
$otherTimes = $cut($get('otherTimes'), 200);
$planSummary = $cut($get('planSummaryText'), 600);
$includeSummary = !empty($in['includeSummary']);
/* The visitor-edited email text (the form shows them the exact
   email, prefilled by the client composer, and they can edit it
   freely). When present it IS the body — see Compose below. */
$message  = $cut($get('message'), 2500);

$asks = (isset($in['asks']) && is_array($in['asks'])) ? $in['asks'] : [];
$askTime = !empty($asks['time']);
$askCov  = !empty($asks['coverage']);
$askCost = !empty($asks['cost']);

$times = [];
if (isset($in['times']) && is_array($in['times'])) {
    foreach ($in['times'] as $t) {
        if (is_string($t) && trim($t) !== '') {
            $times[] = $flat($cut(trim($t), 60));
        }
        if (count($times) >= 9) break;
    }
}

if (!preg_match('/^WF-[A-Z0-9]{5}$/', $caseId)) {
    wf_out(['ok' => false, 'reason' => 'bad_case'], 400);
}
if (!preg_match('/^WF-U-[A-Z0-9]{4}$/', $userId)) {
    wf_out(['ok' => false, 'reason' => 'bad_user'], 400);
}
if ($clinicKey === '' || strpos($clinicKey, '|') === false) {
    wf_out(['ok' => false, 'reason' => 'bad_clinic'], 400);
}
if ($name === '') {
    wf_out(['ok' => false, 'reason' => 'bad_name'], 400);
}
if (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
    wf_out(['ok' => false, 'reason' => 'bad_email'], 400);
}
if (!$askTime && !$askCov && !$askCost) {
    wf_out(['ok' => false, 'reason' => 'no_ask'], 400);
}
if ($treatment === '') {
    $treatment = 'an appointment';
}

/* ---------- Turnstile (only when configured) ---------- */
$cfgPath = __DIR__ . '/portal/config.php';
if (is_file($cfgPath)) {
    include_once $cfgPath; // may define WF_TURNSTILE_SECRET
}
if (defined('WF_TURNSTILE_SECRET') && WF_TURNSTILE_SECRET !== '') {
    $token = $get('turnstileToken');
    $okVerify = false;
    if ($token !== '' && function_exists('curl_init')) {
        $ch = curl_init('https://challenges.cloudflare.com/turnstile/v0/siteverify');
        curl_setopt_array($ch, [
            CURLOPT_POST => true,
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_TIMEOUT => 8,
            CURLOPT_POSTFIELDS => http_build_query([
                'secret' => WF_TURNSTILE_SECRET,
                'response' => $token,
                'remoteip' => $_SERVER['REMOTE_ADDR'] ?? '',
            ]),
        ]);
        $resp = curl_exec($ch);
        curl_close($ch);
        $dec = is_string($resp) ? json_decode($resp, true) : null;
        $okVerify = is_array($dec) && !empty($dec['success']);
    }
    if (!$okVerify) {
        wf_out(['ok' => false, 'reason' => 'verify'], 403);
    }
}

/* ---------- Rate limit: 5 requests / hour / IP ----------
   Counter lives under api/portal/ (deploy-excluded, so it
   persists across deploys). Degrades silently if unwritable. */
$ip = $_SERVER['REMOTE_ADDR'] ?? 'unknown';
$rlFile = __DIR__ . '/portal/wf-ratelimit.json';
$rl = [];
if (is_file($rlFile)) {
    $dec = json_decode((string) file_get_contents($rlFile), true);
    if (is_array($dec)) $rl = $dec;
}
$now = time();
$mine = array_values(array_filter($rl[$ip] ?? [], static function ($ts) use ($now) {
    return is_int($ts) && ($now - $ts) < 3600;
}));
if (count($mine) >= 5) {
    wf_out(['ok' => false, 'reason' => 'rate'], 429);
}
$mine[] = $now;
$rl[$ip] = $mine;
foreach ($rl as $k => $v) { // prune stale IPs so the file stays small
    $fresh = array_values(array_filter((array) $v, static function ($ts) use ($now) {
        return is_int($ts) && ($now - $ts) < 3600;
    }));
    if ($fresh) $rl[$k] = $fresh; else unset($rl[$k]);
}
@file_put_contents($rlFile, json_encode($rl), LOCK_EX);

/* ---------- Resolve the recipient server-side ---------- */
$contactsFile = __DIR__ . '/clinic-contacts.json';
$contacts = [];
if (is_file($contactsFile)) {
    $dec = json_decode((string) file_get_contents($contactsFile), true);
    if (is_array($dec)) $contacts = $dec;
}
$to = $contacts[$clinicKey] ?? '';
if ($to === '' || !filter_var($to, FILTER_VALIDATE_EMAIL)) {
    wf_out(['ok' => false, 'reason' => 'no_email']);
}
if ($clinicName === '') {
    $clinicName = ucwords(str_replace('|', ' — ', $clinicKey));
}

/* ---------- Compose ---------- */
if ($askTime && $askCov) {
    $kind = 'Appointment + coverage question';
} elseif ($askCov) {
    $kind = 'Coverage question';
} else {
    $kind = 'Appointment request';
}
$subject = '[WellFinder] ' . $kind . ' — Case ' . $caseId;

if ($message !== '') {
    /* Visitor-edited path: their text verbatim + the standard
       footer. None of the structured lines below are added, so
       nothing (times, coverage questions, note) is duplicated.
       The subject stays composed from the asks, as before. */
    $body = $message . "\n\n—\n"
        . 'Reply directly to this email to reach ' . $name . ".\n"
        . 'Sent via WellFinder · Case ' . $caseId . ' · Visitor ' . $userId . "\n";
} else {
    /* Legacy path (cached clients without a message): compose
       from the structured fields, exactly as before. */
$lines = [];
$lines[] = 'Hello ' . $clinicName . ' team,';
$lines[] = '';
$lines[] = $name . ' found your clinic on WellFinder.ca and is asking about ' . $treatment . '.';
$lines[] = '';
$q = 0;
if ($askTime) {
    $q++;
    $lines[] = $q . ') Appointment time';
    if ($times) {
        $lines[] = '   Preferred times: ' . implode('; ', $times) . '.';
    }
    if ($otherTimes !== '') {
        $lines[] = '   Also possible: ' . $otherTimes;
    }
    if (!$times && $otherTimes === '') {
        $lines[] = '   They are flexible on timing — please suggest what you have open.';
    }
    $lines[] = '   Could you confirm if one of these works, or suggest the closest alternative?';
    $lines[] = '';
}
if ($askCov) {
    $q++;
    $lines[] = $q . ') Coverage';
    $lines[] = '   Is ' . $treatment . ' billable under their insurance plan?';
    if ($includeSummary && $planSummary !== '') {
        $lines[] = '   From their benefits booklet: ' . $planSummary;
    } elseif ($insurer !== '') {
        $lines[] = '   Their insurer: ' . $insurer . ' (no booklet on file).';
    }
    $lines[] = '';
}
if ($askCost) {
    $q++;
    $lines[] = $q . ') Cost';
    $lines[] = '   What is the total cost for ' . $treatment . '?';
    $lines[] = '';
}
if ($note !== '') {
    $lines[] = 'Note from ' . $name . ':';
    $lines[] = $note;
    $lines[] = '';
}
$lines[] = 'Contact: ' . $name . ' · ' . $email . ($phone !== '' ? ' · ' . $phone : '');
$lines[] = '';
$lines[] = '—';
$lines[] = 'Reply directly to this email to reach ' . $name . '.';
$lines[] = 'Sent via WellFinder · Case ' . $caseId . ' · Visitor ' . $userId;
$body = implode("\n", $lines) . "\n";
}

$headers = implode("\r\n", [
    'From: WellFinder <hello@wellfinder.ca>',
    'Reply-To: ' . $name . ' <' . $email . '>',
    'Content-Type: text/plain; charset=utf-8',
    'X-WellFinder-Case: ' . $caseId,
]);

$sent = @mail($to, $subject, $body, $headers);
if (!$sent) {
    wf_out(['ok' => false, 'reason' => 'send_failed']);
}

wf_out(['ok' => true, 'caseId' => $caseId]);
